    <div className="flex gap-2 items-start px-3 py-2 rounded-lg text-xs" style={{ background: 'rgba(242,101,34,0.08)' }}>
      <span className="text-lg leading-none mt-[-2px]">⚠️</span>
      <span style={{ color: brand.orange }}>{text}</span>
    </div>
