function Stepper({ step }: { step: number }) {
  return (
    <div className="flex items-center min-w-max w-full">
      {STEPS.map((label, i) => {
        const done = i < step; const active = i === step
        const circleCls = done   ? 'bg-[#39B54A] border-[#39B54A] text-white'
                        : active ? 'bg-[#1B5FAE] border-[#1B5FAE] text-white'
                        :          'bg-white border-[#CDDAEE] text-[#5A7AA8]'
        const labelCls  = active ? 'text-[#1B5FAE]' : done ? 'text-[#39B54A]' : 'text-[#5A7AA8]'
        const lineBg    = done ? 'bg-[#39B54A]' : 'bg-[#CDDAEE]'
        return (
          <div key={i} className="flex items-center flex-1">
            <div className="flex flex-col items-center">
              <div className={`w-8 h-8 sm:w-9 sm:h-9 rounded-full flex items-center justify-center text-sm font-bold border-2 transition-all ${circleCls}`}>
                {done ? Ic.check : <span>{i + 1}</span>}
              </div>
              <p className={`text-[10px] sm:text-xs mt-1.5 whitespace-nowrap font-semibold ${labelCls}`}>
                {label}
              </p>
            </div>
            {i < STEPS.length - 1 && (
              <div className={`flex-1 h-0.5 mx-1 sm:mx-2 mb-4 transition-all rounded-full ${lineBg}`} />
            )}
          </div>
        )
      })}
    </div>
  )
}

