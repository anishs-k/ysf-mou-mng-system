// ─── Export helpers ───────────────────────────────────────────────────────────
function downloadCSV(filename: string, headers: string[], rows: string[][]) {
  const escape = (v: string) => `"${v.replace(/"/g, '""')}"`
  const csv = [headers, ...rows].map(r => r.map(escape).join(',')).join('\r\n')
  const blob = new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8;' })
  const url  = URL.createObjectURL(blob)
  const a    = document.createElement('a')
  a.href = url; a.download = filename; a.click()
  URL.revokeObjectURL(url)
}

function printPDF(title: string, bodyHtml: string) {
  const date = new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })
  const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${title}</title>
    <style>
      body { font-family: Arial, sans-serif; color: #0D2E5A; padding: 32px; font-size: 13px; margin: 0; }
      h2 { color: #1B5FAE; margin: 0 0 4px; font-size: 18px; }
      .code { color: #1B5FAE; font-family: monospace; font-size: 12px; margin-bottom: 24px; }
      table { width: 100%; border-collapse: collapse; margin-top: 8px; }
      th { background: #E8F0FB; color: #0D2E5A; font-size: 11px; text-transform: uppercase; letter-spacing: .05em; padding: 8px 12px; text-align: left; border: 1px solid #CDDAEE; }
      td { padding: 9px 12px; border: 1px solid #CDDAEE; vertical-align: top; }
      tr:nth-child(even) td { background: #F7FAFF; }
      .badge { display: inline-block; padding: 2px 8px; border-radius: 4px; font-size: 11px; font-weight: 600; }
      .active  { background: #D1FAE5; color: #065F46; }
      .expired { background: #FEE2E2; color: #991B1B; }
      .footer { margin-top: 32px; font-size: 11px; color: #5A7AA8; border-top: 1px solid #CDDAEE; padding-top: 12px; }
    </style>
  </head><body>${bodyHtml}
    <div class="footer">Generated by YSF MOU Management System · ${date}</div>
  </body></html>`

  const iframe = document.createElement('iframe')
  iframe.style.cssText = 'position:fixed;top:-9999px;left:-9999px;width:1px;height:1px;border:none'
  document.body.appendChild(iframe)
  const doc = iframe.contentDocument ?? iframe.contentWindow?.document
  if (!doc) return
  doc.open(); doc.write(html); doc.close()
  setTimeout(() => {
    iframe.contentWindow?.focus()
    iframe.contentWindow?.print()
    setTimeout(() => document.body.removeChild(iframe), 2000)
  }, 400)
}

